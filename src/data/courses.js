const curriculumTemplate = (topics) =>
  topics.map((section, si) => ({
    id: `s${si + 1}`,
    title: section.title,
    lessons: section.lessons.map((l, li) => ({
      id: `s${si + 1}l${li + 1}`,
      title: l,
      duration: `${6 + ((si + li) % 5) * 3}:${(15 + li * 7) % 60}`.replace(/:(\d)$/, ":0$1"),
    })),
  }));

